    function PerlicaPet(props) {
      const { size: sizeProp, animation: animProp, phaseLine, balance, cost, panelOpen, onTogglePanel, onRefresh, refreshing } = props
      const spriteRef = useRef(null)
      const frameRef = useRef({ anim: null, index: 0, elapsed: 0, done: false })
      const dragRef = useRef(null)
      const [animation, setAnimation] = useState(animProp || 'idle')
      const [effective, setEffective] = useState(animation)
      const [bubble, setBubble] = useState(null)
      const [status, setStatus] = useState(null)
      const statusTimer = useRef(null)
      const [pos, setPos] = useState(() => {
        const saved = loadPos()
        if (saved !== null) return saved
        return { x: Math.max(0, (typeof window !== 'undefined' ? window.innerWidth : 1200) - sizeProp - DEFAULT_MARGIN), y: Math.max(0, (typeof window !== 'undefined' ? window.innerHeight : 800) - sizeProp - DEFAULT_MARGIN) }
      })
      const [dragging, setDragging] = useState(false)
      const [imageReady, setImageReady] = useState(false)

      // Load the atlas once.
      useEffect(() => {
        const img = new Image()
        img.onload = () => setImageReady(true)
        img.src = ATLAS
        return () => {
          img.onload = null
        }
      }, [])

      // Follow the host animation; the effective one may linger on fallbacks.
      useEffect(() => {
        setAnimation(animProp || 'idle')
      }, [animProp])

      useEffect(() => {
        setEffective(animation)
        if (animation !== 'idle') {
          const label = t('pet.status.' + animation)
          if (label) {
            setStatus({ text: label, ts: Date.now() })
            if (statusTimer.current !== null) clearTimeout(statusTimer.current)
            statusTimer.current = setTimeout(() => setStatus(null), STATUS_BUBBLE_MS)
          }
        }
        return () => {
          if (statusTimer.current !== null) clearTimeout(statusTimer.current)
        }
      }, [animation])

      // External phase line (from the host) overrides the translated status.
      useEffect(() => {
        if (typeof phaseLine === 'string' && phaseLine !== '') {
          setStatus({ text: phaseLine, ts: Date.now() })
          if (statusTimer.current !== null) clearTimeout(statusTimer.current)
          statusTimer.current = setTimeout(() => setStatus(null), STATUS_BUBBLE_MS)
        }
      }, [phaseLine])

      const scale = sizeProp / CELL.height

      // The frame loop: advance the track by per-frame durations and paint
      // the background position directly on the sprite element.
      useEffect(() => {
        const el = spriteRef.current
        if (el === null || !imageReady) return
        const reduceMotion = typeof window !== 'undefined' && window.matchMedia?.('(prefers-reduced-motion: reduce)')?.matches === true
        const row = ROW_OF[effective] ?? 0
        const st = frameRef.current
        if (st.anim !== effective) {
          st.anim = effective
          st.index = 0
          st.elapsed = 0
          st.done = false
        }
        const paint = () => {
          const track = TRACKS[effective] ?? TRACKS.idle
          const frame = track.frames[Math.min(st.index, track.frames.length - 1)]
          el.style.backgroundPosition = (-frame * CELL.width * scale).toFixed(2) + 'px ' + (-row * CELL.height * scale).toFixed(2) + 'px'
        }
        paint()
        if (reduceMotion) return undefined
        let raf = 0
        let last = performance.now()
        const tick = (ts) => {
          const delta = ts - last
          last = ts
          const track = TRACKS[effective] ?? TRACKS.idle
          st.elapsed += delta
          const duration = track.durations[Math.min(st.index, track.durations.length - 1)] ?? 120
          if (st.elapsed >= duration) {
            st.elapsed = 0
            if (st.index < track.frames.length - 1) {
              st.index++
            } else if (track.loop) {
              st.index = 0
            } else if (!st.done) {
              st.done = true
              // Non-looping track finished (e.g. jumping on task done): fall
              // back to idle so the pet does not freeze on the last frame.
              setEffective(track.fallback ?? 'idle')
            }
          }
          paint()
          raf = requestAnimationFrame(tick)
        }
        raf = requestAnimationFrame(tick)
        return () => cancelAnimationFrame(raf)
      }, [effective, scale, imageReady])

      // ---- interaction: drag to reposition, click to toggle panel ----
      const clampX = (x) => Math.max(0, Math.min((typeof window !== 'undefined' ? window.innerWidth : 1200) - sizeProp, x))
      const clampY = (y) => Math.max(0, Math.min((typeof window !== 'undefined' ? window.innerHeight : 800) - sizeProp, y))

      const showReaction = useCallback(() => {
        const pick = PET_REACTIONS[Math.floor(Math.random() * PET_REACTIONS.length)]
        setBubble({ text: t(pick), ts: Date.now() })
        setTimeout(() => setBubble(null), 2000)
      }, [])

      const onPointerDown = useCallback((e) => {
        if (e.pointerType === 'mouse' && e.button !== 0) return
        e.preventDefault()
        const saved = loadPos() ?? pos
        dragRef.current = { sx: e.clientX, sy: e.clientY, origin: saved, moved: false }
        setDragging(true)
        window.addEventListener('pointermove', onPointerMove)
        window.addEventListener('pointerup', onPointerUp)
      }, [pos])

      const onPointerMove = useCallback((e) => {
        const d = dragRef.current
        if (d === null) return
        const dx = e.clientX - d.sx
        const dy = e.clientY - d.sy
        if (!d.moved && Math.hypot(dx, dy) < 4) return
        d.moved = true
        setPos({ x: clampX(d.origin.x + dx), y: clampY(d.origin.y + dy) })
      }, [])

      const onPointerUp = useCallback(() => {
        const d = dragRef.current
        window.removeEventListener('pointermove', onPointerMove)
        window.removeEventListener('pointerup', onPointerUp)
        dragRef.current = null
        setDragging(false)
        if (d !== null && !d.moved) {
          showReaction()
          onTogglePanel()
        }
        if (d !== null && d.moved) {
          setPos((p) => {
            savePos(p.x, p.y)
            return p
          })
        }
      }, [onPointerMove, showReaction, onTogglePanel])

      useEffect(() => () => {
        window.removeEventListener('pointermove', onPointerMove)
        window.removeEventListener('pointerup', onPointerUp)
      }, [onPointerMove, onPointerUp])

      const spriteStyle = {
        width: (CELL.width * scale).toFixed(1) + 'px',
        height: (CELL.height * scale).toFixed(1) + 'px',
        backgroundImage: 'url(' + ATLAS + ')',
        backgroundSize: (ATLAS_WIDTH * scale).toFixed(1) + 'px ' + (ATLAS_HEIGHT * scale).toFixed(1) + 'px',
        backgroundRepeat: 'no-repeat',
      }
      const floatStyle = {
        position: 'fixed',
        left: pos.x + 'px',
        top: pos.y + 'px',
        zIndex: 2147483000,
      }

      return h(
        'div',
        { className: 'dshpp-float' + (dragging ? ' dshpp-dragging' : ''), style: floatStyle, onPointerDown: onPointerDown },
        bubble !== null ? h('div', { key: 'b-' + bubble.ts, className: 'dshpp-bubble dshpp-bubble-reaction' }, bubble.text) : null,
        status !== null && status.ts !== bubble?.ts ? h('div', { key: 's-' + status.ts, className: 'dshpp-bubble' }, status.text) : null,
        h('div', { ref: spriteRef, className: 'dshpp-sprite', style: spriteStyle }),
        panelOpen ? h(UsagePanel, { balance, cost, onClose: onTogglePanel, onRefresh, refreshing }) : null
      )
    }

